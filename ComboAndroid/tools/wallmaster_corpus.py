class ShipRandom:
    """SoH's randomizer stream (rng.h, ShipUtils.cpp RandInit, next32, Random and Shuffle)."""

    def __init__(self, seed):
        self.state = seed & MASK64

    def next32(self):
        self.state = (self.state * 6364136223846793005 + 11634580027462260723) & MASK64
        value = (((self.state >> 18) ^ self.state) >> 27) & 0xffffffff
        rotation = self.state >> 59
        return ((value >> rotation) | (value << (32 - rotation))) & 0xffffffff

    def random(self, low, high):  # [low, high - 1]
        if low == high:
            return low
        span = high - low
        cutoff = 0xffffffff - 0xffffffff % span
        while True:
            value = self.next32()
            if value <= cutoff:
                return low + value % span

    def shuffle(self, items):
        for i in range(len(items) - 1):
            j = self.random(i, len(items))
            items[i], items[j] = items[j], items[i]


def mq_roll(master, cvars):
    """The Master Quest dungeons (a DungeonKey bit mask) that a bundled seed with these OoT CVars rolls from the master
    seed of its attempt: settings.cpp Context::FinalizeSettings on the stream of MqMode.h MqRollSeed. Absent CVars
    take the menu defaults: None, a count of 12, Set Dungeon Quests off, every dungeon Vanilla."""
    mode = cvars.get('gRandoSettings.MQDungeons', 0)
    count = cvars.get('gRandoSettings.MQDungeonCount', 12)
    presets = [cvars.get(key, 0) for key in MQ_QUEST_CVARS]
    rng = ShipRandom(combo_hash(f'mqDungeons:{MQ_SOURCE}:{master}'))
    mq = set()
    if mode == 3:  # Selection Only: Master Quest, or a coin flip for each Random dungeon
        for i, preset in enumerate(presets):
            if preset == 1 or (preset == 2 and rng.random(0, 2)):
                mq.add(i)
    elif mode in (1, 2):  # Set Number or Random Number, from the dungeons Set Dungeon Quests leaves Random
        chosen, candidates = 0, []
        if cvars.get('gRandoSettings.MQDungeonsSelection', 0):
            for i, preset in enumerate(presets):
                if preset == 1:
                    mq.add(i)
                    chosen += 1
                elif preset == 2:
                    candidates.append(i)
        elif mode == 1 and count == 0:
            return 0
        else:
            candidates = list(range(len(MQ_DUNGEONS)))
        if candidates:
            if mode == 2:
                picks = rng.random(0, len(candidates) + 1)
            else:
                picks = min(count - chosen, len(candidates)) if count > chosen else 0
            if 0 < picks <= len(candidates):
                rng.shuffle(candidates)
            mq.update(candidates[:picks])
    return sum(1 << i for i in mq)


def mq_names(mask):
    return [name for i, name in enumerate(MQ_DUNGEONS) if mask & (1 << i)]


def capacity_shortfall(mask):
    """Master Quest Spirit Temple and Bottom of the Well with vanilla Shadow Temple and Ganon's Castle: 12 OoT
    Wallmasters for 11 dungeon entrances (UnifiedBridge.h RequireWallmasterCapacity)."""
    return all(bool(mask & (1 << MQ_INDEX[d])) == mq for d, mq in (('Spirit', True), ('BotW', True),
                                                                  ('Shadow', False), ('Ganon', False)))


def shortfall_forced(cvars):
    """EntranceProfile.h MqRollRange and MqWallmasterShortfallForced: every roll of these settings is a shortfall."""
    mode = cvars.get('gRandoSettings.MQDungeons', 0)
    presets = [cvars.get(key, 0) for key in MQ_QUEST_CVARS]
    quests = ['vanilla'] * len(MQ_DUNGEONS)
    if mode == 3:
        quests = ['mq' if p == 1 else 'either' if p == 2 else 'vanilla' for p in presets]
    elif mode in (1, 2):
        chosen, candidates = 0, []
        for i in range(len(MQ_DUNGEONS)):
            preset = presets[i] if cvars.get('gRandoSettings.MQDungeonsSelection', 0) else 2
            if preset == 1:
                quests[i], chosen = 'mq', chosen + 1
            elif preset == 2:
                candidates.append(i)
        picks = (max(0, min(cvars.get('gRandoSettings.MQDungeonCount', 12) - chosen, len(candidates)))
                 if mode == 1 else -1)
        for i in candidates:
            quests[i] = 'vanilla' if picks == 0 else 'mq' if picks == len(candidates) else 'either'
    return all(quests[MQ_INDEX[d]] == q for d, q in (('Spirit', 'mq'), ('BotW', 'mq'), ('Shadow', 'vanilla'),
                                                      ('Ganon', 'vanilla')))


