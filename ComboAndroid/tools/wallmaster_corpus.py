def nest_cvars(flat):
    """{"a.b.c": v} as the nested CVars block of comboship.json."""
    root = {}
    for key, value in sorted(flat.items()):
        node, parts = root, key.split('.')
        for part in parts[:-1]:
            node = node.setdefault(part, {})
            if not isinstance(node, dict):
                stop(f'CVar {key} nests under a value')
        if parts[-1] in node:
            stop(f'CVar {key} is both a value and a group')
        node[parts[-1]] = value
    return {'CVars': root}


def flat_cvars(config_json):
    flat = {}

    def walk(prefix, node):
        for key, value in node.items():
            name = f'{prefix}.{key}' if prefix else key
            if isinstance(value, dict):
                walk(name, value)
            else:
                flat[name] = value
    walk('', config_json.get('CVars', {}))
    return flat


