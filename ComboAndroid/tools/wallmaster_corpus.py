def host_only_path(path):
    """Files the fixture commit may change besides the fixtures: host tests and tools, never another fixture, and the
    .gitattributes line that keeps the fixture bytes exact."""
    return path == '.gitattributes' or (path.startswith(('ComboAndroid/tests/', 'ComboAndroid/tools/')) and
                                        not path.startswith('ComboAndroid/tests/fixtures/'))


def cmd_provenance_0413(args):
    rc = git(args.repo, 'rev-parse', '--verify', args.rc + '^{commit}')
    fixture = git(args.repo, 'rev-parse', '--verify', args.fixtures_commit + '^{commit}')
    if not descends(args.repo, rc, fixture):
        stop(f'{fixture} does not descend from the release candidate {rc}')
    changed = git(args.repo, 'diff', '--name-only', rc, fixture).splitlines()
    manifest = json.loads(git(args.repo, 'show', f'{fixture}:{FIXTURES_0413}/manifest.json'))
    if manifest.get('schema') != MANIFEST_SCHEMA_0413 or manifest['release']['sourceCommit'] != rc:
        stop(f'the manifest at {fixture[:12]} does not name the release candidate {rc}')
    reasons = {}
    for entry in manifest.get('hostOnlyFiles', []):
        path, reason = entry.get('path'), entry.get('reason')
        if not isinstance(path, str) or path in reasons or not host_only_path(path) or not one_line(reason):
            stop(f'bad host-only entry {entry!r}: a host test or tool (or .gitattributes) and a one-line reason')
        reasons[path] = reason
    fixtures = [p for p in changed if p.startswith(FIXTURES_0413 + '/')]
    outside = [p for p in changed if not p.startswith(FIXTURES_0413 + '/')]
    missing, extra = sorted(set(outside) - set(reasons)), sorted(set(reasons) - set(outside))
    if not fixtures or missing or extra:
        stop(f'{fixture[:12]} must change {FIXTURES_0413}/ and exactly the host-only files its manifest lists: '
             f'not listed {missing}, listed but unchanged {extra}')
    if '.gitattributes' in reasons:
        lines = [line for line in git(args.repo, 'diff', '-U0', rc, fixture, '--', '.gitattributes').splitlines()
                 if line[:1] in '+-' and not line.startswith(('+++', '---'))]
        if any(not line.startswith('+') or FIXTURES_0413 not in line and not line.startswith('+#') for line in lines):
            stop(f'.gitattributes changes more than lines for {FIXTURES_0413}: {lines}')
    print(git(args.repo, 'log', '--oneline', f'{rc}..{fixture}'))
    print(git(args.repo, 'diff', '--stat', rc, fixture))
    for path in sorted(reasons):
        print(f'  host-only {path}: {reasons[path]}')
    print(f'PASS: {fixture[:12]} differs from the release candidate {rc[:12]} in {len(fixtures)} files under '
          f'{FIXTURES_0413}/ and {len(reasons)} host-only files, each listed in its manifest with a reason; the '
          f'manifest names that commit.')


