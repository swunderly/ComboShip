def cmd_add_save(args):
    fixtures = args.fixtures.resolve()
    manifest = load(fixtures/'manifest.json')
    row = next((seed for seed in manifest['seeds'] if seed['id'] == args.seed), None)
    if row is None:
        stop(f'{args.seed} is not a corpus seed of {fixtures}')
    doc = load(fixtures/row['seed'])
    data = args.save.read_bytes()
    container = json.loads(data)
    combo = container.get('combo') if isinstance(container, dict) else None
    if not isinstance(combo, dict) or container.get('slot') != 2:
        stop(f'{args.save} is not a File 3 container (slot 2)')
    rando = combo.get('rando')
    if isinstance(rando, str):
        rando = json.loads(rando)
    if rando != doc:
        differing = sorted(key for key in set(doc) | set(rando or {}) if (rando or {}).get(key) != doc.get(key))
        stop(f'the saved seed is not {args.seed}; differing keys: {differing}. Do not edit the save: report it.')
    if not isinstance(container.get('oot'), dict) or not isinstance(container.get('mm'), dict) or \
            combo.get('visitedGames', 0) & 3 != 3:
        stop('the save was not created and played in both games (oot and mm pages, visitedGames 3)')
    if combo.get('notes', '') != '':
        stop('the save has personal notes; make a new throwaway save without notes')
    name = f'saves/file3-{args.seed}.combosav'
    if (fixtures/name).exists() or any(save['corpusSeed'] == args.seed for save in manifest['saves']):
        stop(f'{name} is already a fixture')
    (fixtures/'saves').mkdir(exist_ok=True)
    (fixtures/name).write_bytes(data)
    manifest['saves'].append({'id': f'file3-{args.seed}', 'file': name, 'slot': 2, 'corpusSeed': args.seed,
                              'checkpoint': args.checkpoint, 'playerName': args.player_name})
    refresh_files(fixtures, manifest)
    print(f'Added {name} ({len(data)} bytes, SHA-256 {sha256(data)}) for {args.seed}.')


# ---- provenance ------------------------------------------------------------------------------------------------------
def git(repo, *command):
    return subprocess.run(['git', '-C', str(repo), *command], check=True, capture_output=True,
                          text=True).stdout.strip()


def outside_fixtures(paths):
    return [path for path in paths if not path.startswith(FIXTURES + '/')]


def descends(repo, ancestor, commit):
    return subprocess.run(['git', '-C', str(repo), 'merge-base', '--is-ancestor', ancestor, commit]).returncode == 0


def later_release(manifest, commit):
    return next((r for r in manifest.get('laterReleases', []) if r.get('sourceCommit') == commit), None)


def one_line(reason):
    return isinstance(reason, str) and reason.strip() != '' and '\n' not in reason and '\r' not in reason


def check_later_release(repo, manifest, rc):
    """A later release candidate rc may use the corpus only when (a) the manifest records it, (b) every file it changes
    since the corpus's release candidate is a fixture or on its allowlist with a one-line reason, and (c) its own
    comborando regenerated the recorded sample rows byte for byte. Returns what passed."""
    corpus = manifest['release']['sourceCommit']
    record = later_release(manifest, rc)
    if record is None:
        stop(f'the manifest records source commit {corpus}, not {rc}, and no later release candidate {rc}')
    if not descends(repo, corpus, rc):
        stop(f'the later release candidate {rc} does not descend from the corpus\'s release candidate {corpus}')
    reasons = {}
    for entry in record.get('outsideGeneration', []):
        path, reason = entry.get('path'), entry.get('reason')
        if not isinstance(path, str) or path in reasons or not outside_fixtures([path]) or not one_line(reason):
            stop(f'{rc[:12]}: bad allowlist entry {entry!r}; each file needs a path and a one-line reason')
        reasons[path] = reason
    changed = outside_fixtures(git(repo, 'diff', '--name-only', corpus, rc).splitlines())
    unlisted = [path for path in changed if path not in reasons]
    if unlisted:
        stop(f'{rc[:12]} changes files since {corpus[:12]} that its allowlist does not list: {unlisted}')
    sample = record.get('sample') or {}
    rows = sample.get('rows') or []
    if sample.get('status') != 'identical':
        stop(f'PENDING: no regenerated sample for {rc[:12]} yet. Regenerate the rows {rows} with its comborando '
             f'(SHA-256 {record.get("comborandoSha256")}) and record them with the sample command.')
    hashes = {entry['path']: entry['sha256'] for entry in manifest['files']}
    seeds = {seed['id']: seed for seed in manifest['seeds']}
    results = {result.get('id'): result for result in sample.get('results', [])}
    if not rows or sorted(results) != sorted(rows) or len(set(rows)) != len(rows) or \
            sample.get('comborandoSha256') != record.get('comborandoSha256'):
        stop(f'{rc[:12]}: the recorded sample does not cover its rows with that release candidate\'s comborando')
    for rid in rows:
        if rid not in seeds or results[rid].get('seedSha256') != hashes.get(seeds[rid]['seed']) or \
                results[rid].get('entrancesSha256') != hashes.get(seeds[rid]['entrances']):
            stop(f'{rc[:12]}: the regenerated {rid} is not the corpus row byte for byte')
    return (f'it is a later release candidate of the corpus\'s {corpus[:12]}: its {len(changed)} changed files outside '
            f'the fixtures are all on its allowlist, and its comborando regenerated {len(rows)} sample rows byte for '
            f'byte.')


def cmd_provenance(args):
    rc = git(args.repo, 'rev-parse', '--verify', args.rc + '^{commit}')
    fixture = git(args.repo, 'rev-parse', '--verify', args.fixtures_commit + '^{commit}')
    if not descends(args.repo, rc, fixture):
        stop(f'{fixture} does not descend from the release candidate {rc}')
    changed = git(args.repo, 'diff', '--name-only', rc, fixture).splitlines()
    outside = outside_fixtures(changed)
    if not changed or outside:
        stop(f'the fixture commit changes files outside {FIXTURES}/: {outside or "nothing at all"}')
    manifest = json.loads(git(args.repo, 'show', f'{fixture}:{FIXTURES}/manifest.json'))
    named = 'its manifest names that commit.'
    if manifest['release']['sourceCommit'] != rc:
        named = check_later_release(args.repo, manifest, rc)
    print(git(args.repo, 'log', '--oneline', f'{rc}..{fixture}'))
    print(git(args.repo, 'diff', '--stat', rc, fixture))
    print(f'PASS: {fixture[:12]} differs from the release candidate {rc[:12]} only in {len(changed)} files under '
          f'{FIXTURES}/, and {named}')


