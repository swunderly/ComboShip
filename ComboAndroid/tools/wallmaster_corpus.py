#!/usr/bin/env python3
"""Plan, collect and record the release-built Wallmaster Shuffle corpus (M1 plan P1-11; fixtures for P1-06).

  plan        Stage the release candidate's libraries (from its APK) and comborando, the settings configs, the device
              scripts and plan.json, the exact command lines of every row, into a new bundle directory.
  manifest    Turn the results pulled from the emulator into ComboAndroid/tests/fixtures/wallmasters-vanilla-v1/.
  add-save    Add an exported File 3 save (file3.combosav) the app made from a corpus seed.
  provenance  Show that the fixture commit differs from the release candidate's source commit only in the fixtures. A
              later release candidate passes only once later-rc and sample have recorded it.
  later-rc    Record a later release candidate in the manifest: each file it changes outside the fixtures since the
              corpus's release candidate, with a one-line reason why it is outside seed generation, and the corpus rows
              its own comborando must regenerate. The sample stays pending until sample records it.
  sample      Record those rows, regenerated by the later release candidate's comborando, once each matches its
              fixture byte for byte.

The 0.4.13 corpus (ComboAndroid/tests/fixtures/wallmasters-0413/) has its own commands:
  plan-0413        Stage the 0.4.13 bundle: Wallmaster seeds of each capability id (cross-game songs, a starting OoT
                   warp song, Master Quest dungeons), the capacity refusals, Master Quest seeds without Wallmaster
                   Shuffle, No Logic seeds and 0.4.12 corpus rows regenerated by the 0.4.13 generator.
  manifest-0413    Check the pulled results row by row (capability id, scene restriction marker, Master Quest
                   dungeons, refusal sentences, the regenerated 0.4.12 rows against their fixtures) and write the
                   fixture directory.
  provenance-0413  Show that the fixture commit differs from the corpus's current release candidate (its own, or the
                   last later one it records) only in that directory and in the allowlisted host-only files, each
                   with its one-line reason.
  plan-rc-0413     Stage a later release candidate's device run: the rows it changes (regenerated in full), the
                   recorded refusal failures, replays of the seeds whose recorded replay failed, and a sample of rows
                   its generator must make byte for byte.
  later-rc-0413    Record it pending: each file it changes outside the fixtures, with its effect on generation
                   (unchanged, or expected for the rows it regenerates) and a one-line reason.
  sample-0413      Check its pulled results and record them: the regenerated rows replace their fixtures (madeBy), and
                   the host-only files become those the fixture commit changes since this release candidate.
                   A later release candidate may be of a later version (0.4.14 RC1 for the 0.4.13 corpus), and its
                   sample also remakes every row an earlier one regenerated (a07 and d06 since RC2).

The 0.4.14 corpus (ComboAndroid/tests/fixtures/wallmasters-0414/), Full Wallmaster Shuffle (erWallmasters=full,
wallmasters-full-v1), has its own:
  plan-0414        Stage the 0.4.14 bundle: Full seeds with vanilla and Master Quest dungeons (the Spirit Temple and
                   Bottom of the Well context Own Game refuses among them), cross-game songs and Ageless Soaring, a
                   starting OoT warp song, Cross-Games Age and No Logic, and 0.4.12 corpus rows regenerated with
                   their own command line, which must equal the 0.4.13 corpus's regenerations byte for byte.
  manifest-0414    Check the pulled results row by row (the Full id and LayoutV2 setting, both games' Wallmasters on
                   distinct ones of the 18 shared destinations, the routes into the other game and their lines in
                   OoTMM's entrance spoiler text, oot.resolvedChoices exactly when a random choice exists) and write
                   the fixture directory.
  provenance-0414  Show that the fixture commit differs from the release candidate only in that directory and in the
                   allowlisted host-only files, each with a reason; an earlier corpus's manifest may only gain this
                   release candidate's later-release record.

Nothing here runs on or talks to a device. The device scripts run headless only: comborando, no app, no save and
no gameplay. ComboAndroid/tests/entrance_corpus_tests.py checks the 0.4.12 fixtures this writes,
ComboAndroid/tests/entrance_corpus_0413_tests.py the 0.4.13 ones and entrance_corpus_0414_tests.py the 0.4.14 ones.
"""
