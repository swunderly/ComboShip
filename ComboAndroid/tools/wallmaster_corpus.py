def json_diff(old, new, path=()):
    """Every place two JSON values differ: (path, added | removed | changed, old, new)."""
    if isinstance(old, dict) and isinstance(new, dict):
        out = []
        for key in sorted(set(old) | set(new)):
            if key not in old:
                out.append((path + (key,), 'added', None, new[key]))
            elif key not in new:
                out.append((path + (key,), 'removed', old[key], None))
            else:
                out += json_diff(old[key], new[key], path + (key,))
        return out
    if isinstance(old, list) and isinstance(new, list) and len(old) == len(new):
        return [d for i, (a, b) in enumerate(zip(old, new)) for d in json_diff(a, b, path + (i,))]
    return [] if old == new else [(path, 'changed', old, new)]


def logic_key(rule):
    """GameplayRules.h LogicRuleKey."""
    special = {'gEnhancements.BlueFireArrows': 'gRandoSettings.BlueFireArrows',
               'gEnhancements.SunlightArrows': 'gRandoSettings.SunlightArrows',
               'gCombo.Enhancements.ForeignSongs': 'gCombo.Rando.ForeignSongs',
               'gCombo.Enhancements.SongTravel': 'gCombo.Rando.SongTravel'}
    return special.get(rule, 'gCombo.Logic.' + rule)


def settings_facts(doc, cvars):
    """(problems, notes): the required settings the seed does not record as requested, and every other config value
    its dumps show differently."""
    oot, mm = doc['oot']['settings'], doc['mm']['settings']
    rules = doc.get('gameplayRules') or {}
    problems, notes = [], []
    for key, value in sorted(cvars.items()):
        if key in MQ_QUEST_CVARS or key.startswith('gRandoSettings.MQDungeon'):
            continue  # the finalize rewrites them; the rolled dungeons are checked instead
        if key.startswith('gRandoSettings.') and key in oot:
            seen = oot[key]
        elif key.startswith('gRando.') and key in mm:
            seen = mm[key]
        else:
            continue
        if key == 'gRando.ExcludedChecks' and isinstance(seen, list) and isinstance(value, list):
            seen, value = sorted(seen), sorted(value)  # MM's dump lists them in check order (BenPort.cpp)
        if seen != value:
            (problems if key in REQUIRED_OOT_SETTINGS + REQUIRED_MM_SETTINGS else notes).append(
                {'setting': key, 'requested': value, 'recorded': seen})
    for rule in REQUIRED_RULES:
        logical, runtime = cvars.get(logic_key(rule), 0), cvars.get(rule, 0)
        if (rules.get('logicValues') or {}).get(rule) != logical or (rules.get('values') or {}).get(rule) != runtime:
            problems.append({'rule': rule, 'requested': [logical, runtime],
                             'recorded': [(rules.get('logicValues') or {}).get(rule),
                                          (rules.get('values') or {}).get(rule)]})
    songs = doc.get('songTravel') or {}
    if songs.get('logicForeignSongs') != bool(cvars.get('gCombo.Rando.ForeignSongs', 0)) or songs.get('logicEnabled'):
        problems.append({'songTravel': {k: songs.get(k) for k in ('logicEnabled', 'logicForeignSongs')}})
    return problems, notes


def refusal_lines(row, expect, attempt=0):
    master = (row['masterSeed'] + attempt * GOLDEN) % (1 << 32)
    return [f'[comborando] seed {master}: WALLMASTERS has 12 sources for 11 destinations; OoTMM cannot place them',
            REFUSAL_PREFIX + expect['sentence']]


def refusal_attempt(row, expect, lines):
    """The fill attempt whose shortfall stopped generation, read from its log, or None: the first attempt for a seed's
    own roll, any attempt for a forced one, whose first attempt can fail earlier for a reason a retry clears
    (UnifiedBridge.h WallmasterShortfallStopsGeneration, since 0.4.13 RC2)."""
    attempts = range(FILL_ATTEMPTS) if expect['sentence'] == FORCED_SENTENCE else range(1)
    return next((k for k in attempts if all(line in lines for line in refusal_lines(row, expect, k))), None)


