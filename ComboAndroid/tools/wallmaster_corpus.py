def shortfall_forced(cvars):
    """EntranceProfile.h MqRollRange and MqWallmasterShortfallForced: every roll of these settings is a shortfall."""
    mode = cvars.get('gRandoSettings.MQDungeons', 0)
    presets = [cvars.get(key, 0) for key in MQ_QUEST_CVARS]
    quests = ['vanilla'] * len(MQ_DUNGEONS)
    if mode == 3:
        quests = ['mq' if p == 1 else 'either' if p == 2 else 'vanilla' for p in presets]
    elif mode in (1, 2):
        chosen, candidates = 0, []
        for i in range(len(MQ_DUNGEONS)):
            preset = presets[i] if cvars.get('gRandoSettings.MQDungeonsSelection', 0) else 2
            if preset == 1:
                quests[i], chosen = 'mq', chosen + 1
            elif preset == 2:
                candidates.append(i)
        picks = (max(0, min(cvars.get('gRandoSettings.MQDungeonCount', 12) - chosen, len(candidates)))
                 if mode == 1 else -1)
        for i in candidates:
            quests[i] = 'vanilla' if picks == 0 else 'mq' if picks == len(candidates) else 'either'
    return all(quests[MQ_INDEX[d]] == q for d, q in (('Spirit', 'mq'), ('BotW', 'mq'), ('Shadow', 'vanilla'),
                                                      ('Ganon', 'vanilla')))


