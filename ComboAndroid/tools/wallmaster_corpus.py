def sample_rows(manifest):
    """The rows a later release candidate regenerates: the first of each settings config and start request, and the
    fallback search's Random start."""
    chosen = {}
    for seed in sorted(manifest['seeds'], key=lambda s: s['id']):
        chosen.setdefault((seed['config'], seed['request']['startingGame']), seed['id'])
    rows = sorted(chosen.values())
    found = (manifest.get('fallbackSearch') or {}).get('found')
    if found and found not in rows:
        rows.append(found)
    return rows


def cmd_later_rc(args):
    fixtures = args.fixtures.resolve()
    manifest = load(fixtures/'manifest.json')
