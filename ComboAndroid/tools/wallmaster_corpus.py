def one_line_map_of(path):
    """{path: {"generation": "unchanged" | "expected", "reason": one line}}."""
    values = load(path)
    if not isinstance(values, dict) or not all(
            isinstance(entry, dict) and set(entry) == {'generation', 'reason'} and
            entry['generation'] in GENERATION_EFFECTS and one_line(entry['reason']) for entry in values.values()):
        stop(f'{path} must map each changed file to {{"generation": "unchanged" | "expected", "reason": one line}}')
    return values


