    missing, extra = sorted(set(changed) - set(reasons)), sorted(set(reasons) - set(changed))
    if missing or extra:
        stop(f'the allowlist must name exactly the files {rc[:12]} changes outside {FIXTURES}/ since {corpus[:12]}: '
             f'without a reason {missing}, not changed {extra}')
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    import verify_apk  # the release gate: refuses an entrance dev build
    verify_apk.verify(args.apk)
