inline bool MmGrottoBound(std::string_view name) {
    for (const auto& row : kMmGrottoGraphBindings)
        if (row.name == name)
            return true;
    return false;
}
inline bool MmGrottoNativeAreaExists(std::string_view area) {
    for (const auto& row : kMmGrottoGraphBindings) {
        const auto* r = Find(row.name);
        if (r->from == area || r->to == area)
            return true;
    }
    return false;
}
inline bool IsMmGrottoRecord(const Record* r) {
    return r && r->game == Game::Mm &&
           (r->type == Type::Grotto || r->type == Type::GrottoExit || r->type == Type::Grave ||
            r->type == Type::GraveExit);
}
inline bool MmGrottoInput(const Record& r) {
    return r.type == Type::Grotto || r.type == Type::Grave;
}
