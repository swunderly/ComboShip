"""Export hidden entrance setting metadata from the exact OoTMM v32.3 Git blob.

Usage: python tools/ootmm/export_entrance_settings.py --reference PATH [--check]
No checkout mutation, network, or TypeScript runtime is needed. Unsupported syntax
is rejected instead of partially importing an upstream setting.
"""
from pathlib import Path
import argparse
import ast
import hashlib
import json
import re
import subprocess

PIN = '413573d22d1d53e8a81931a70927f625b73488b9'
SOURCE = 'packages/core/src/settings/data.ts'
EXCLUDED = {'erWarps', 'erOneWaysSongs', 'erOneWaysStatues', 'erOneWaysWoods'}
ROOT = Path(__file__).resolve().parents[2]
STRING = r"'(?:[^'\\]|\\.)*'"


def quoted(block, field):
    match = re.search(r'^  ' + field + r': (' + STRING + r')', block, re.M)
    if not match:
        raise ValueError(f'Missing {field}')
    return ast.literal_eval(match[1])


def records(source):
    result = []
    for block in source.split('\n}, {\n'):
        if "  category: 'entrances'" not in block:
            continue
        key = quoted(block, 'key')
        kind = quoted(block, 'type')
        default = re.search(r'^  default: ([^,\n]+)', block, re.M)[1]
        if default not in ('false', "'none'") or kind not in ('boolean', 'enum'):
            raise ValueError(f'Unexpected type/default at {key}')
        cond = re.search(r'^  cond: (.*?)(?:,)?$', block, re.M)
        condition = cond[1].rstrip(',') if cond else ''
        values = []
        if kind == 'enum':
            value_block = re.search(r'^  values: \[\n(.*?)^  \]', block, re.M | re.S)[1]
            for row in value_block.splitlines():
                m = re.fullmatch(r'    \{ value: (' + STRING + r'), name: (' + STRING + r')(.*?) \},', row)
                if not m:
                    raise ValueError(f'Unrecognized enum row at {key}: {row}')
                description = re.search(r', description: (' + STRING + r')', m[3])
                value_cond = re.search(r', cond: (\w+)', m[3])
                remainder = re.sub(r', description: ' + STRING + r'|, cond: \w+', '', m[3])
                if remainder:
                    raise ValueError(f'Unrecognized enum field at {key}')
                values.append({'value': ast.literal_eval(m[1]), 'name': ast.literal_eval(m[2]),
                               'description': ast.literal_eval(description[1]) if description else '',
                               'condition': value_cond[1] if value_cond else ''})
        result.append({'key': key, 'name': quoted(block, 'name'), 'type': kind,
                       'description': quoted(block, 'description'), 'default': False if kind == 'boolean' else 'none',
                       'condition': condition, 'values': values, 'inScope': key not in EXCLUDED})
    if len(result) != 44 or {r['key'] for r in result} & EXCLUDED != EXCLUDED:
        raise ValueError(f'Unexpected entrance setting catalog: {len(result)} rows')
    return result


def cpp_condition(condition):
    if not condition:
        return 'true'
    if condition in ('hasOoT', 'hasMM', 'hasOoTMM'):
        return 'true'  # ComboShip's model always contains both games.
    expression = re.sub(r'^\([xs]: any\) => ', '', condition)
    expression = re.sub(r'has(?:OoTMM|OoT|MM)\([xs]\)', 'true', expression)
    def enum_comparison(match):
        key, op, value = match.groups()
        kind = 'Warps' if key == 'erWarps' else 'Spawns' if key == 'erSpawns' else 'Mode'
        names = {'none': 'None', 'ownGame': 'OwnGame', 'full': 'Full',
                 'ootOnly': 'OotOnly', 'mmOnly': 'MmOnly', 'child': 'Child', 'adult': 'Adult', 'both': 'Both'}
        return f's.{key} {"==" if op == "===" else "!="} {kind}::{names[value]}'
    expression = re.sub(r"[xs]\.(\w+)\s*(===|!==)\s*'([^']+)'", enum_comparison, expression)
    expression = re.sub(r'\b[xs]\.', 's.', expression).replace('===', '==').replace('!==', '!=')
    if re.search(r"[^\w\s.:()!&|=]", expression):
        raise ValueError(f'Unsupported condition: {condition}')
    return expression


def generate(rows, digest):
    q = lambda text: json.dumps(text.replace('<br>', '\n'), ensure_ascii=True)
    lines = ['// Generated by tools/ootmm/export_entrance_settings.py from OoTMM v32.3.',
             '// MIT; see LICENSE.OoTMM. Do not edit generated metadata.',
             f'inline constexpr std::string_view kEntranceSettingsCommit = "{PIN}";',
             f'inline constexpr std::string_view kEntranceSettingsSourceSha256 = "{digest}";']
    for row in rows:
        if not row['inScope'] or not row['values']:
            continue
        lines.append(f'inline constexpr EntranceChoice kChoices_{row["key"]}[] = {{')
        for value in row['values']:
            lines.append('    {' + ', '.join(q(value[k]) for k in ('value', 'name', 'description')) + '},')
        lines.append('};')
    lines.append('inline constexpr EntranceSetting kEntranceSettings[] = {')
    for row in rows:
        if not row['inScope']:
            continue
        key = row['key']
        choices = f'kChoices_{key}' if row['values'] else 'kBooleanChoices'
        condition = cpp_condition(row['condition'])
        args = ', '.join([q(key), q('gCombo.Rando.Entrances.' + key), q(row['name']), q(row['description']), choices])
        lines.append(f'    MakeEntranceSetting<&Settings::{key}>({args},')
        lines.append(f'        [](const Settings& s) {{ (void)s; return {condition}; }}),')
    lines += ['};', '']
    return '\n'.join(lines)


def export(reference, root, check):
    head = subprocess.check_output(['git', '-C', str(reference), 'rev-parse', 'HEAD'], text=True).strip()
    if head != PIN:
        raise ValueError(f'Expected OoTMM v32.3 at {PIN}, got {head}')
    blob = subprocess.check_output(['git', '-C', str(reference), 'show', f'{PIN}:{SOURCE}'])
    digest = hashlib.sha256(blob).hexdigest()
    rows = records(blob.decode('utf-8'))
    fixture = {'upstreamCommit': PIN, 'source': SOURCE, 'sourceSha256': digest, 'settings': rows}
    outputs = {
        root / 'combo/rando/entrances/OotmmSettingsData.inc': generate(rows, digest),
        root / 'ComboAndroid/tests/fixtures/ootmm-32.3-entrance-settings.json': json.dumps(fixture, indent=2) + '\n',
    }
    for path, content in outputs.items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                raise ValueError(f'Stale generated file: {path}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(content, encoding='utf-8', newline='\n')
    print(f'{"Verified" if check else "Exported"} {len(rows)} settings, {sum(r["inScope"] for r in rows)} in scope, all hidden.')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--reference', type=Path, required=True)
    parser.add_argument('--root', type=Path, default=ROOT)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    export(args.reference, args.root, args.check)
