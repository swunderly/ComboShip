"""Export the 22 verified source predicates (11 vanilla, 11 MQ) and the bound source names; no capability."""
from pathlib import Path
import hashlib
import json
import export_oot_wallmaster_edges as audit_tool
from export_registry import PIN, arguments, publish

REPO = Path(__file__).resolve().parents[2]
AUDIT = 'tools/ootmm/oot-wallmaster-anchor-audit.json'
JSON = 'tools/ootmm/oot-wallmaster-overlay.json'
INC = 'soh/soh/Enhancements/randomizer/combo_oot_wallmaster_edges.inc'
NAMES = 'combo/rando/entrances/OotWallmasterSourceNames.h'


def build(reference):
    fixture = audit_tool.build(reference)
    raw = (REPO / AUDIT).read_bytes()
    audit = json.loads(raw)
    errors = audit_tool.verify_audit(audit, fixture, REPO,
        audit_tool.contract.pinned_blobs(reference, audit_tool.pinned_items(audit)))
    errors += audit_tool.verify_mq_rooms(audit)
    if errors:
        raise ValueError('Anchor audit does not hold: ' + '; '.join(errors))
    allowed = set(audit['workList']['M1-14'])
    rows = [e for e in audit['edges'] if e['id'] in allowed]
    vanilla = [e for e in rows if e['quest'] == 'vanilla']
    mq = [e for e in rows if e['quest'] == 'mq']
    if len(vanilla) != 11 or len(mq) != 11 or any(
            e['status'] != 'ready' or e['actorRoom']['status'] != 'verified' for e in rows):
        raise ValueError('Expected eleven ready vanilla and eleven ready MQ edges with verified actor rooms')
    if [e['status'] for e in audit['edges'] if e['id'] not in allowed] != ['false']:
        raise ValueError('Every edge but the false one must be ready')
    if len({e['source'] for e in vanilla}) != 9 or len({e['source'] for e in rows}) != 13:
        raise ValueError('Expected nine vanilla source identities and thirteen in all')
    dungeons = {e['id']: e['dungeon'] for e in fixture['edges']}
    return {'upstreamCommit': PIN, 'auditSha256': hashlib.sha256(raw).hexdigest(),
            'scope': 'Eleven vanilla and eleven Master Quest verified source predicates; an MQ edge is anchored in '
                     'its MQ dungeon\'s native regions, so it applies only where that dungeon is MQ. No capability '
                     'is admitted.',
            'edges': [{'n': e['n'], 'id': e['id'], 'quest': e['quest'], 'dungeon': dungeons[e['id']],
                       'source': e['source'], 'anchor': e['anchor']['region'], 'condition': e['condition']['native']}
                      for e in rows]}


def outputs(value):
    banner = ['// Generated by tools/ootmm/export_oot_wallmaster_overlay.py; do not hand-edit.',
              '// Pinned OoTMM ' + value['upstreamCommit'] + '; verified anchors and actor rooms only.']
    inc = banner + ['// Edge id, source identity, native anchor, original audited predicate. The MQ edges',
                    '// (dungeons_mq) are anchored in MQ regions, which only a Master Quest dungeon reaches.']
    for edge in value['edges']:
        inc += [f'{{ "{edge["id"]}", "{edge["source"]}", {edge["anchor"]}, [] {{',
                '    auto ctx = Rando::Context::GetInstance();', '    auto logic = Rando::ActiveLogic();',
                f'    return {edge["condition"]};', '} },']
    vanilla = sorted({e['source'] for e in value['edges'] if e['quest'] == 'vanilla'})
    every = sorted({e['source'] for e in value['edges']})
    names = banner + ['#pragma once', '#include <array>', '#include <string_view>', '',
                      'namespace ComboRando::Entrances {',
                      '// The sources of an all-vanilla OoT, which the frozen vanilla capability binds.',
                      f'inline constexpr std::array<std::string_view, {len(vanilla)}> kOotVanillaWallmasterSources = {{',
                      *[f'    "{source}",' for source in vanilla], '};',
                      '// Every OoT Wallmaster source with a verified edge: the ones above and the ones only a Master',
                      '// Quest dungeon has.',
                      f'inline constexpr std::array<std::string_view, {len(every)}> kOotWallmasterSources = {{',
                      *[f'    "{source}",' for source in every], '};',
                      '// The dungeon (EntranceLayout.h kOotMqDungeons) and quest of each edge in',
                      '// combo_oot_wallmaster_edges.inc, by audit id: an edge applies where its dungeon has its quest.',
                      'struct OotWallmasterEdgeQuest {',
                      '    std::string_view auditId, dungeon;',
                      '    bool mq;',
                      '};',
                      f'inline constexpr std::array<OotWallmasterEdgeQuest, {len(value["edges"])}> '
                      'kOotWallmasterEdgeQuests = { {',
                      *[f'    {{ "{e["id"]}", "{e["dungeon"]}", {"true" if e["quest"] == "mq" else "false"} }},'
                        for e in value['edges']], '} };',
                      '} // namespace ComboRando::Entrances']
    return {JSON: (json.dumps(value, indent=2) + '\n').encode(), INC: ('\n'.join(inc) + '\n').encode(),
            NAMES: ('\n'.join(names) + '\n').encode()}


if __name__ == '__main__':
    args = arguments(__doc__)
    publish(args.output_root, outputs(build(args.reference)), args.check)
    print('Verified eleven vanilla and eleven MQ Wallmaster predicates and thirteen source identities.')
