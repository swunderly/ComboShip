"""Derive MM grotto arrival/exit context from exact OoTMM v32.3 runtime Git blobs."""
import hashlib
import json
import re
from export_registry import PIN, arguments, initializer, json_bytes, publish, read_registry, verified_blob

RUNTIME_SOURCE = 'packages/generator/src/mm/play/play.c'


def parse_context(original, records):
    source = original.decode('utf-8')
    table = re.search(r'static const GrottoExit kGrottoExits\[\] = \{(.*?)\n\};', source, re.S)[1]
    pattern = r'\{\s*ENTR_(MM_[A-Z0-9_]+),\s*(\d+),\s*\{\s*(-?\d+),\s*(-?\d+),\s*(-?\d+)\s*\}\s*\}'
    entries = re.findall(pattern, table)
    without_entries = re.sub(pattern + ',?', '', table)
    without_comments = re.sub(r'/\*.*?\*/', '', without_entries, flags=re.S)
    if len(entries) != 24 or without_comments.strip():
        raise RuntimeError('MM grotto exit table count or syntax drift')
    generic = re.search(r'static const u8 kGrottoDataGeneric\[\] = \{([^}]+)\};', source)[1]
    codes = [int(value.strip(), 0) for value in generic.split(',')]
    if len(codes) != 13 or len(set(codes)) != 13 or any(not 0 <= code <= 255 for code in codes):
        raise RuntimeError('MM generic grotto codes drift')
    winter = re.search(r'kGrottoExitMountainWinter =\s*(' + pattern + r');', source).groups()[1:]
    by_name = {entry['name']: entry for entry in records}
    by_id = {(entry['game'], entry['id']): entry for entry in records}
    for index in range(24):
        if by_id[('mm', 0x10100 + index)]['type'] != 'grotto-exit':
            raise RuntimeError('MM grotto exit logical ID order changed')
    for name, room, x, y, z in [*entries, winter]:
        record = by_name[name]
        if record['game'] != 'mm' or record['id'] > 0xffff or not 0 <= int(room) <= 255:
            raise RuntimeError('Non-native grotto exit target or room')
        if any(not -32768 <= int(value) <= 32767 for value in (x, y, z)):
            raise RuntimeError('Grotto exit coordinate exceeds native range')
    return {'upstreamCommit': PIN, 'runtimeSource': RUNTIME_SOURCE,
            'runtimeSourceSha256': hashlib.sha256(original).hexdigest(),
            'genericCodes': codes, 'exitEntries': entries, 'winterEntry': winter}


def context_header(manifest, records):
    by_name = {entry['name']: entry for entry in records}
    lines = ['// Derived from OoTMM v32.3 mm/play/play.c; see LICENSE.OoTMM.',
             '// Generated by tools/ootmm/export_grotto_context.py; do not hand-edit.',
             '#pragma once', '#include "Registry.h"', 'namespace ComboRando::Entrances {',
             'inline constexpr std::string_view kGrottoRuntimeSourceSha256 =',
             '    ' + json.dumps(manifest['runtimeSourceSha256']) + ';',
             'struct GrottoExitData {', '    std::string_view entranceName;',
             '    uint16_t nativeEntrance;', '    uint8_t room;', '    int16_t x, y, z;', '};',
             '// clang-format off',
             'inline constexpr std::array<uint8_t, 13> kMmGenericGrottoData = {',
             '    ' + ', '.join(hex(code) for code in manifest['genericCodes']) + '\n};',
             'inline constexpr std::array<GrottoExitData, 24> kMmGrottoExits = { {']
    for name, *values in manifest['exitEntries']:
        lines.append(initializer([json.dumps(name), hex(by_name[name]['id']), *values]))
    name, *values = manifest['winterEntry']
    lines += ['} };', 'inline constexpr GrottoExitData kMmGrottoExitMountainWinter = {',
              '    ' + ', '.join([json.dumps(name), hex(by_name[name]['id']), *values]) + '\n};',
              '// clang-format on', '} // namespace ComboRando::Entrances', '']
    return '\n'.join(lines).encode('utf-8')


def main():
    args = arguments(__doc__)
    _, records = read_registry(args.reference)
    original = verified_blob(args.reference, RUNTIME_SOURCE)
    manifest = parse_context(original, records)
    publish(args.output_root, {
        'combo/rando/entrances/GrottoMetadata.h': context_header(manifest, records),
        'tools/ootmm/grotto-context-source.json': json_bytes(manifest),
    }, args.check)
    print(f'{"Verified" if args.check else "Exported"} 13 codes, 24 MM exits and the winter exception from {PIN}')


if __name__ == '__main__':
    main()
